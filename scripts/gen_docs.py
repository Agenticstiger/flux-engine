"""Generate the reference pages that have one source of truth in the code.

Three sets of pages under ``docs/reference/`` are never written by hand:

* ``cli/``: one page per command, and an index, from the argparse tree that
  ``fluxsim --help`` prints. The pages are built from the parser's *structure*
  (its actions, their help strings, the examples attached to each parser), not
  from ``format_help()`` output, so they come out the same on Python 3.11, 3.12
  and 3.13: argparse's text layout is not stable across those versions, its
  structure is.
* ``schemas.md``: the schemas this version validates against, from the ones it vendors,
  so the page moves in the same commit that moves the pin to a newer specification.
* ``errors/``: one page per ``FLX-nnnn`` code, and an index, from the catalog
  that ``fluxsim explain`` reads. The pattern is Ruff's rule pages and the Rust
  error index: the text lives where the code is registered, and the site gets
  the same text, one stable address per code.

Run with no arguments to rewrite the pages. ``--check`` changes nothing and
exits 1 when any page is missing, differs from what the code would generate, or
is left over from a code or command that no longer exists. ``make docs-check``
runs it, and so does ``tests/docs/test_generated_docs.py``, which is what makes
a stale page fail CI.

The pages are VuePress 2 Markdown: front matter, relative ``.md`` links, and
prose escaped so that ``<`` and ``{{`` outside a code span cannot be read as a
Vue template. They are written once and never edited: the first comment in each
says where to change the text.
"""

from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, Iterable, List, Optional, Sequence, Tuple

REPO_ROOT = Path(__file__).resolve().parent.parent
DOCS_ROOT = REPO_ROOT / "docs"

#: Directories under ``docs/`` whose every ``*.md`` is generated, and so is checked for strays.
GENERATED_DIRECTORIES: Tuple[str, ...] = ("reference/cli", "reference/errors")

_GENERATED = "<!-- Generated by scripts/gen_docs.py from {source}. Do not edit this page. -->"


class GenerationError(Exception):
    """The code and the generator disagree about something only a person can settle."""


# --------------------------------------------------------------------------- text helpers

_CODE_SPAN = re.compile(r"(`[^`\n]+`)")


def _escape_text(text: str) -> str:
    return (
        text.replace("{{", "&#123;&#123;")
        .replace("}}", "&#125;&#125;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
    )


def prose(text: str) -> str:
    """*text* made safe for a VuePress page: escaped everywhere except inside code spans."""
    return "".join(
        part if _CODE_SPAN.fullmatch(part) else _escape_text(part)
        for part in _CODE_SPAN.split(text)
    )


def _cell(text: str) -> str:
    """Prose for a table cell: a pipe would end the cell."""
    return prose(" ".join(text.split())).replace("|", "\\|")


def _yaml(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _front_matter(title: str, description: str) -> str:
    return f"---\ntitle: {_yaml(title)}\ndescription: {_yaml(description)}\neditLink: false\n---\n"


# --------------------------------------------------------------------------- error pages


def error_pages() -> Dict[str, str]:
    """``reference/errors/*.md``: one page per catalog code, and the index."""
    from flux_engine.core.errors import CATEGORIES, catalog, ensure_core_codes_loaded

    ensure_core_codes_loaded()
    entries = catalog()
    source = (
        "the error catalog (flux_engine.core.errors); change the text where the code is registered"
    )
    pages: Dict[str, str] = {}
    for entry in entries:
        pages[f"reference/errors/{entry.code}.md"] = "\n".join(
            [
                _front_matter(entry.code, entry.title),
                _GENERATED.format(source=source),
                "",
                f"# {entry.code}: {prose(entry.title)}",
                "",
                f"**Family:** {entry.category} (the {entry.band} band)",
                "",
                prose(entry.explanation),
                "",
                "## Look it up offline",
                "",
                "```console",
                f"$ fluxsim explain {entry.code}",
                "```",
                "",
                "Every code is listed in the [error index](./README.md).",
                "",
            ]
        )

    lines = [
        _front_matter("Error codes", "Every FLX-nnnn code the engine reports, by family."),
        _GENERATED.format(source=source),
        "",
        "# Error codes",
        "",
        "A failure the engine can name carries an `FLX-nnnn` code. The thousands digit says "
        "which part of the engine raised it. `fluxsim explain FLX-nnnn` prints the same text "
        "offline, and `fluxsim explain --list` lists every code.",
        "",
    ]
    for band, family in CATEGORIES.items():
        in_band = [entry for entry in entries if entry.band == band]
        if not in_band:
            continue
        lines += [f"## {band}: {family}", "", "| Code | What it means |", "|---|---|"]
        lines += [f"| [{e.code}](./{e.code}.md) | {_cell(e.title)} |" for e in in_band]
        lines.append("")
    pages["reference/errors/README.md"] = "\n".join(lines)
    return pages


# --------------------------------------------------------------------------- command pages


@dataclass(frozen=True)
class _Option:
    flags: str
    value: str
    required: bool
    help: str


@dataclass(frozen=True)
class _Argument:
    name: str
    optional: bool
    help: str


def _subparsers(parser: argparse.ArgumentParser) -> Dict[str, argparse.ArgumentParser]:
    found: Dict[str, argparse.ArgumentParser] = {}
    for action in parser._actions:  # noqa: SLF001 - argparse introspection idiom
        if isinstance(action, argparse._SubParsersAction):  # noqa: SLF001
            found.update(action.choices)
    return found


def _help_of(action: argparse.Action) -> str:
    return " ".join((action.help or "").split())


def _arguments(parser: argparse.ArgumentParser) -> List[_Argument]:
    found = []
    for action in parser._actions:  # noqa: SLF001
        if isinstance(action, (argparse._HelpAction, argparse._SubParsersAction)):  # noqa: SLF001
            continue
        if action.option_strings:
            continue
        found.append(
            _Argument(
                name=str(action.metavar or action.dest),
                optional=action.nargs in ("?", "*"),
                help=_help_of(action),
            )
        )
    return found


def _options(parser: argparse.ArgumentParser) -> List[_Option]:
    found = []
    for action in parser._actions:  # noqa: SLF001
        if isinstance(action, argparse._HelpAction) or not action.option_strings:  # noqa: SLF001
            continue
        takes_value = action.nargs != 0
        value = str(action.metavar or action.dest.upper()) if takes_value else ""
        found.append(
            _Option(
                ", ".join(action.option_strings), value, bool(action.required), _help_of(action)
            )
        )
    return found


def _synopsis(parser: argparse.ArgumentParser) -> str:
    parts = [parser.prog]
    if _subparsers(parser):
        parts.append("<command>")
    if _options(parser):
        parts.append("[options]")
    parts += [f"[<{a.name}>]" if a.optional else f"<{a.name}>" for a in _arguments(parser)]
    return " ".join(parts)


def _examples_block(parser: argparse.ArgumentParser) -> List[str]:
    examples = getattr(parser, "examples", ())
    if not examples:
        return []
    lines = ["```bash"]
    for position, example in enumerate(examples):
        if position:
            lines.append("")
        if example.note:
            lines.append(f"# {example.note}")
        lines += [line.rstrip() for line in example.command.split("\n")]
    lines += ["```"]
    return lines


def _command_section(parser: argparse.ArgumentParser, level: int, *, whole_page: bool) -> List[str]:
    """The body of one command: description, synopsis, examples, arguments, options."""
    mark = "#" * level
    lines: List[str] = []
    if not whole_page:
        lines += [f"{'#' * (level - 1)} `{parser.prog}`", ""]
    if parser.description:
        lines += [prose(" ".join(parser.description.split())), ""]
    lines += [f"{mark} Synopsis", "", "```text", _synopsis(parser), "```", ""]
    block = _examples_block(parser)
    if block:
        lines += [f"{mark} Examples", ""] + block + [""]
    arguments = _arguments(parser)
    if arguments:
        lines += [f"{mark} Arguments", "", "| Argument | Description |", "|---|---|"]
        lines += [
            f"| `{a.name}`{' (optional)' if a.optional else ''} | {_cell(a.help)} |"
            for a in arguments
        ]
        lines.append("")
    options = _options(parser)
    if options:
        lines += [f"{mark} Options", "", "| Option | Value | Description |", "|---|---|---|"]
        for o in options:
            required = " **(required)**" if o.required else ""
            value = f"`{o.value}`" if o.value else ""
            lines.append(f"| `{o.flags}` | {value} | {_cell(o.help)}{required} |")
        lines.append("")
    return lines


def _anchor(prog: str) -> str:
    return re.sub(r"[^a-z0-9-]+", "", prog.lower().replace(" ", "-"))


#: The exit codes, as the module docstring of ``flux_engine.cli`` states them.
_EXIT_CODES = (
    ("0", "The command ran and succeeded."),
    (
        "1",
        "The command ran and failed. The message says why; a catalogued failure carries an `FLX-nnnn` code.",
    ),
    ("2", "A usage error: the command line itself was wrong, so nothing ran."),
    ("3", "`fluxsim gate decide` only: the request was decided, and the policy said no."),
)

#: The environment variables the command line reads.
_ENVIRONMENT = (
    (
        "FLUX_ZONE",
        "The run's declared zone for sovereignty checks, used when `--zone` is not given.",
    ),
    ("FLUX_DEBUG", "Any non-empty value prints the traceback of an unexpected failure."),
    (
        "FLUX_NO_PROGRESS",
        "Any non-empty value silences the progress lines and the `next:` hints that a terminal "
        "otherwise gets on stderr.",
    ),
)


def cli_pages() -> Dict[str, str]:
    """``reference/cli/*.md``: one page per top-level command, and the index."""
    from flux_engine.cli import build_parser

    root = build_parser()
    source = "the argparse tree of fluxsim (flux_engine.cli); change the text there"
    commands = _subparsers(root)
    pages: Dict[str, str] = {}

    for name, parser in commands.items():
        nested = _subparsers(parser)
        description = _help_for(root, name) or name
        lines = [
            _front_matter(f"fluxsim {name}", description),
            _GENERATED.format(source=source),
            "",
            f"# `fluxsim {name}`",
            "",
        ]
        if nested:
            if parser.description:
                lines += [prose(" ".join(parser.description.split())), ""]
            lines += ["## Commands", "", "| Command | What it does |", "|---|---|"]
            for child_name in nested:
                label = f"fluxsim {name} {child_name}"
                help_text = _help_for(parser, child_name)
                lines.append(f"| [`{label}`](#{_anchor(label)}) | {_cell(help_text)} |")
            lines.append("")
            for child in nested.values():
                lines += _command_section(child, 3, whole_page=False)
        else:
            lines += _command_section(parser, 2, whole_page=True)
        lines += ["[All commands](./README.md)", ""]
        pages[f"reference/cli/{name}.md"] = "\n".join(lines)

    pages["reference/cli/README.md"] = _cli_index(root, commands, source)
    return pages


def _help_for(parser: argparse.ArgumentParser, child: str) -> str:
    for action in parser._actions:  # noqa: SLF001
        if isinstance(action, argparse._SubParsersAction):  # noqa: SLF001
            for sub in action._get_subactions():  # noqa: SLF001
                if sub.dest == child or sub.metavar == child:
                    return sub.help or ""
    return ""


def _cli_index(
    root: argparse.ArgumentParser, commands: Dict[str, argparse.ArgumentParser], source: str
) -> str:
    lines = [
        _front_matter(
            "Command line", "Every fluxsim command, its options, exit codes and environment."
        ),
        _GENERATED.format(source=source),
        "",
        "# Command line",
        "",
        prose(" ".join((root.description or "").split())),
        "",
        "```bash",
    ]
    for position, example in enumerate(getattr(root, "examples", ())):
        if position:
            lines.append("")
        if example.note:
            lines.append(f"# {example.note}")
        lines += [line.rstrip() for line in example.command.split("\n")]
    lines += ["```", "", "## Commands", "", "| Command | What it does |", "|---|---|"]
    for name in commands:
        lines.append(f"| [`fluxsim {name}`](./{name}.md) | {_cell(_help_for(root, name))} |")
    lines += ["", "## Options every command accepts", "", "| Option | Description |", "|---|---|"]
    for option in _options(root):
        lines.append(f"| `{option.flags}` | {_cell(option.help)} |")
    lines += [
        "",
        "`--json` and `-j` may come before or after the command.",
        "",
        "## The JSON envelope",
        "",
        "With `--json` every command prints one document of the same shape, so a caller never has "
        "to guess which command produced it or read stderr for the reason it failed:",
        "",
        "```json",
        "{",
        '  "stage": "validate",',
        '  "exitCode": 0,',
        '  "ok": true,',
        '  "artifacts": {},',
        '  "error": null',
        "}",
        "```",
        "",
        "`artifacts` is the command's own output. `error` is `null` on success, otherwise "
        '`{"code": "FLX-nnnn", "message": "..."}`, where `code` is `null` for a failure with no '
        "catalogued code. A usage error is an envelope too, with `exitCode` 2.",
        "",
        "## Exit codes",
        "",
        "| Code | Meaning |",
        "|---|---|",
    ]
    lines += [f"| `{code}` | {_cell(meaning)} |" for code, meaning in _EXIT_CODES]
    lines += ["", "## Environment", "", "| Variable | Effect |", "|---|---|"]
    lines += [f"| `{name}` | {_cell(effect)} |" for name, effect in _ENVIRONMENT]
    lines += ["", "[All error codes](../errors/README.md)", ""]
    return "\n".join(lines)


# --------------------------------------------------------------------------- schemas page

_FLUX_SCHEMA_PURPOSE = {
    "flux-schema": "Every FLUX document: its kind, its fields, and the rules that hold inside one document.",
    "flux-enforcement": "The decision object the RFC-04 enforcement gate returns for one request.",
    "flux-manifest": "The manifest of an evidence archive: the files, their digests and the Merkle root.",
    "flux-ui-hints": "Hints for editors that build forms from the schema.",
}

_FLUX_SCHEMA_URL = "https://agenticstiger.github.io/flux/schema/{name}"


def _current_schema_file(directory: Path, stem: str, spec_version: str) -> Optional[str]:
    """The newest ``<stem>-X.Y.Z.json`` in *directory* at or below *spec_version*.

    A specification release republishes only the schemas it changed: FLUX 0.5.1
    widened the document schema and kept the 0.5.0 enforcement and manifest
    contracts, so the current file of each family is its newest version that
    does not postdate the specification, not one file name per release.
    """

    def version_of(path: Path) -> Tuple[int, ...]:
        return tuple(int(part) for part in path.stem.removeprefix(f"{stem}-").split("."))

    ceiling = tuple(int(part) for part in spec_version.split("."))
    candidates = [
        path
        for path in directory.glob(f"{stem}-*.json")
        if re.fullmatch(rf"{re.escape(stem)}-\d+\.\d+\.\d+", path.stem)
        and version_of(path) <= ceiling
    ]
    return max(candidates, key=version_of).name if candidates else None


def schemas_page() -> Dict[str, str]:
    """``reference/schemas.md``: the schemas this version validates against, by versioned address.

    Built from the schemas the engine vendors, so the page changes in the same commit
    that moves the pin to a newer specification, and the drift gate sees it.
    """
    import json

    import flux_engine._vendor.flux_spec as vendored
    from flux_engine.describe import VENDORED_SPEC_VERSION
    from flux_engine.spec import SUPPORTED_SPEC_VERSION_RANGE

    base = Path(vendored.__file__).resolve().parent
    flux_rows = []
    for stem, purpose in _FLUX_SCHEMA_PURPOSE.items():
        name = _current_schema_file(base / "schema", stem, VENDORED_SPEC_VERSION)
        if name is None:
            # A page that quietly lost a row would still match its own output, and the
            # drift gate would pass. Say it instead: the pin moved to a specification
            # that names its files differently, and this table has to follow.
            raise GenerationError(
                f"the vendored specification has no {stem}-*.json at or below "
                f"{VENDORED_SPEC_VERSION}; update _FLUX_SCHEMA_PURPOSE in scripts/gen_docs.py "
                "to the files it ships"
            )
        flux_rows.append(f"| [{name}]({_FLUX_SCHEMA_URL.format(name=name)}) | {_cell(purpose)} |")
    flux_schema = json.loads(
        (base / "schema" / f"flux-schema-{VENDORED_SPEC_VERSION}.json").read_text(encoding="utf-8")
    )
    accepted_flux_versions = flux_schema["properties"]["fluxVersion"]["enum"]
    fluid_rows = []
    fluid_versions = []
    for path in sorted((base / "vendor" / "fluid").glob("fluid-schema-*.json")):
        document = json.loads(path.read_text(encoding="utf-8"))
        version = path.stem.removeprefix("fluid-schema-")
        fluid_versions.append(version)
        address = (
            document.get("$id") or f"https://open-data-protocol.github.io/fluid/schema/{path.name}"
        )
        fluid_rows.append(
            f"| [{path.name}]({address}) | {_cell(str(document.get('title', version)))} |"
        )

    lines = [
        _front_matter(
            "Schemas",
            "The FLUX and FLUID schemas this version of the engine validates against, with links fixed to a version.",
        ),
        _GENERATED.format(
            source="the schemas this version vendors (flux_engine/_vendor/flux_spec); "
            "they change when the pin moves to a newer specification"
        ),
        "",
        "# Schemas",
        "",
        f"This version of the engine implements **FLUX {VENDORED_SPEC_VERSION}** and accepts "
        f"specification releases in the range `{SUPPORTED_SPEC_VERSION_RANGE}`; "
        "`fluxsim describe --self` reports the one that is running. The FLUX schema accepts "
        "documents that declare a `fluxVersion` of "
        f"{', '.join(f'`{v}`' for v in accepted_flux_versions)}, and refuses any other. "
        "A FLUID contract is checked against the schema of its own `fluidVersion`, from the "
        f"versions this release carries: {', '.join(f'**{v}**' for v in fluid_versions)}.",
        "",
        "Each link has the version in its file name, so it does not move when a newer "
        "specification is published. This page is generated, and it changes in the same commit "
        "that moves the engine to a newer specification.",
        "",
        "A schema is only the first layer. The validator then checks what no schema can: that "
        "every reference resolves, every id is unique, every weight sums, and that a "
        "Simulation's emits agree with the FLUID contract they refer to.",
        "",
        f"## FLUX {VENDORED_SPEC_VERSION}",
        "",
        "| Schema | What it checks |",
        "|---|---|",
        *flux_rows,
        "",
        "## FLUID",
        "",
        "| Schema | Title |",
        "|---|---|",
        *fluid_rows,
        "",
    ]
    return {"reference/schemas.md": "\n".join(lines)}


# --------------------------------------------------------------------------- driver


def generate() -> Dict[str, str]:
    """Every generated page, keyed by its path under ``docs/``."""
    pages: Dict[str, str] = {}
    pages.update(cli_pages())
    pages.update(error_pages())
    pages.update(schemas_page())
    return pages


def _stale(root: Path, wanted: Iterable[str]) -> List[str]:
    keep = set(wanted)
    found = []
    for directory in GENERATED_DIRECTORIES:
        base = root / directory
        if base.is_dir():
            for path in sorted(base.glob("*.md")):
                relative = path.relative_to(root).as_posix()
                if relative not in keep:
                    found.append(relative)
    return found


def check(root: Path = DOCS_ROOT) -> List[str]:
    """What is wrong with the generated pages on disk under *root*; empty means current."""
    pages = generate()
    problems = []
    for relative, content in sorted(pages.items()):
        path = root / relative
        if not path.is_file():
            problems.append(f"missing: {relative}")
        elif path.read_text(encoding="utf-8") != content:
            problems.append(f"differs from what the code generates: {relative}")
    problems += [f"stale, nothing generates it: {relative}" for relative in _stale(root, pages)]
    return problems


def write(root: Path = DOCS_ROOT) -> List[str]:
    """Rewrite every generated page under *root*, remove strays, return the paths changed."""
    pages = generate()
    changed = []
    for relative, content in sorted(pages.items()):
        path = root / relative
        if path.is_file() and path.read_text(encoding="utf-8") == content:
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8", newline="\n")
        changed.append(relative)
    for relative in _stale(root, pages):
        (root / relative).unlink()
        changed.append(f"{relative} (removed)")
    return changed


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=(__doc__ or "").split("\n\n", 1)[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="change nothing; exit 1 if any generated page is missing, differs or is stale",
    )
    args = parser.parse_args(argv)
    try:
        if args.check:
            problems = check()
            if problems:
                print("generated docs are out of date; run `make docs-gen`:", file=sys.stderr)
                for problem in problems:
                    print(f"  {problem}", file=sys.stderr)
                return 1
            print(f"generated docs are current ({len(generate())} pages)")
            return 0
        changed = write()
    except GenerationError as error:
        print(f"gen_docs: {error}", file=sys.stderr)
        return 1
    print(f"wrote {len(changed)} page(s)" if changed else "generated docs were already current")
    for relative in changed:
        print(f"  {relative}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
