"""Which exposes a generator plugin generates, and what this release cannot combine with one.

ADR 0032 section 5: the engine derives an expose's identifier and key columns and draws its foreign
keys, and the plugin generates every other column. A construct that would set one of the plugin's
columns, or read one of its values before the plugin has given them, cannot be applied to such an
expose in this release, and is refused (``FLX-3105``) rather than supported halfway:

* a rule or a copy that sets a column (a ``derive``, a dependency, a difference form a ``generates``
  setting turns into a column, or a ``sharedColumns`` or ``sharedAttribute`` copy), since every
  column the engine does not derive is the plugin's;
* a rule that holds a window over the row's siblings, reads a linked row, or declares a band, and a
  dependency;
* a column drawn ``given`` another, when either is a plugin column;
* a ``reference: true`` expose, whose rows are the profile's, and an expose with no column for a
  plugin to generate;
* a rule of any expose, a column drawn ``given`` a linked column, or a weighted foreign key whose
  weight is a plugin column, that reads a row of such an expose through a link.

``plan``, ``validate`` and ``fluxsim init``'s pre-flight call the one function, so they refuse alike.
"""

from __future__ import annotations

from typing import Any, Dict, List, Mapping, Optional, Sequence, Set, Tuple

from flux_engine.core.errors import FluxError
from flux_engine.expr2.errors import Expr2Error
from flux_engine.generator.plugin import PluginExpose, plugin_expose
from flux_engine.generator.relations import related_columns
from flux_engine.generator.rules import FORM_DEPENDENCY, RulePlan, parent_condition
from flux_engine.generator.statistics import statistics_from_fidelity
from flux_engine.seam.counts import count_entries_of
from flux_engine.seam.coverage import printable
from flux_engine.seam.generators import GeneratorDeclaration
from flux_engine.seam.keys import compile_keys
from flux_engine.seam.links import link_entries_of
from flux_engine.seam.resolve import FLX_3105, ResolvedEmit

__all__ = ["plugin_exposes", "refuse_plugin_combinations"]


def plugin_exposes(
    resolved_emits: Sequence[ResolvedEmit], declarations: Sequence[GeneratorDeclaration]
) -> Dict[str, PluginExpose]:
    """The columns a plugin generates, for every emit the Simulation declares a plugin for."""
    declared = {item.expose_id for item in declarations}
    found: Dict[str, PluginExpose] = {}
    for resolved in resolved_emits:
        if resolved.expose_id not in declared:
            continue
        expose = resolved.compile()
        found[resolved.expose_id] = plugin_expose(
            expose,
            statistics_from_fidelity(expose, resolved.fidelity),
            related_columns(resolved.keys),
        )
    return found


def _refusal(here: str, reason: str) -> FluxError:
    return FluxError(
        FLX_3105,
        f"{here}: {reason}; a generator plugin's expose cannot combine with it in this release",
    )


def refuse_plugin_combinations(
    resolved: ResolvedEmit,
    rules: Optional[RulePlan],
    plugins: Mapping[str, PluginExpose],
    *,
    where: str,
) -> None:
    """Refuse (``FLX-3105``) what an emit declares that its plugin exposes cannot take.

    *plugins* is every plugin expose of the Simulation (:func:`plugin_exposes`), *rules* the emit's
    rules as :func:`flux_engine.stages.pipeline.plan_emit_rules` plans them.
    """
    if not plugins:
        return
    own = plugins.get(resolved.expose_id)
    if own is not None:
        _refuse_own(resolved, rules, own, where=where)
    _refuse_reads(resolved, rules, plugins, where=where)


def _refuse_own(
    resolved: ResolvedEmit, rules: Optional[RulePlan], own: PluginExpose, *, where: str
) -> None:
    here = f"{printable(where)}: emit {resolved.expose_id!r} is generated by a plugin"
    if resolved.is_reference:
        raise _refusal(here, "it also declares reference: true, so its rows are the profile's")
    if not own.columns:
        raise _refusal(
            here,
            "every column is an identifier, a key or a foreign key, which the engine derives, "
            "so there is nothing for the plugin to generate",
        )
    names = set(own.names)
    if rules is not None:
        if rules.order:
            raise _refusal(
                here,
                "a rule or a copy sets "
                + ", ".join(repr(name) for name in rules.order)
                + ", and the plugin generates every column the engine does not derive",
            )
        if rules.windowed:
            raise _refusal(here, "a rule holds a window over the row's siblings")
        for rule in rules.rules:
            if rule.form == FORM_DEPENDENCY:
                raise _refusal(here, f"rule {rule.id!r} is a dependency")
            if rule.paths:
                raise _refusal(here, f"rule {rule.id!r} reads a row a link reaches")
            if rule.band is not None:
                raise _refusal(
                    here,
                    f"rule {rule.id!r} declares a band, and the engine holds a plugin's values to "
                    "a check on every row it covers",
                )
    expose = resolved.compile()
    statistics = statistics_from_fidelity(expose, resolved.fidelity)
    for column in expose.columns:
        _refuse_column_given(column.name, statistics[column.name], names, here)


def _refuse_column_given(name: str, given: Any, names: Set[str], here: str) -> None:
    """Refuse a column the plugin generates, or one drawn given a column it generates."""
    linked = [] if given.given_link is None else [given.given_link[1]]
    if given.allocation is not None and name in names:
        raise _refusal(
            here,
            f"column {name!r} declares allocation: exact, and the plugin generates "
            "its values, so the engine has no levels to allot",
        )
    parents = [*given.parents, *linked]
    if parents and (name in names or any(parent in names for parent in parents)):
        raise _refusal(here, f"column {name!r} is drawn given another column")


def _paths_of(
    resolved: ResolvedEmit, rules: Optional[RulePlan]
) -> Tuple[List[Tuple[str, ...]], Dict[str, str]]:
    """The relationship paths an emit reads rows through, and the weight column of each weighted one."""
    paths: List[Tuple[str, ...]] = []
    if rules is not None:
        paths.extend(path for rule in rules.rules for path in rule.paths)
    weights: Dict[str, str] = {}
    expose = resolved.compile()
    for given in statistics_from_fidelity(expose, resolved.fidelity).values():
        if given.given_link is not None:
            paths.append((given.given_link[0],))
    for entry in link_entries_of(resolved.extension, resolved.expose_id):
        if entry.weight is not None:
            weights[entry.relationship] = entry.weight
    return paths, weights


def _refuse_parent_whens(
    resolved: ResolvedEmit, keys: Any, plugins: Mapping[str, PluginExpose], here: str
) -> None:
    """Refuse a counts ``parentWhen`` of *resolved* that reads a column a plugin generates."""
    for entry in count_entries_of(resolved.extension, resolved.expose_id):
        if entry.parent_when is None:
            continue
        relationship = next(
            (
                item
                for item in keys.expose(resolved.expose_id).relationships
                if item.name == entry.relationship
            ),
            None,
        )
        target = None if relationship is None else plugins.get(relationship.target)
        if relationship is None or target is None:
            continue
        try:
            condition, _ = parent_condition(
                resolved.contract_document, relationship.target, entry.parent_when
            )
        except Expr2Error:
            continue  # the relation step refuses a text that does not check, naming its key
        read = sorted(set(condition.reads) & set(target.names))
        if read:
            raise _refusal(
                here,
                f"counts[{resolved.expose_id}.{entry.relationship}].parentWhen reads "
                f"{', '.join(repr(name) for name in read)} of {relationship.target!r}, an expose "
                "a plugin generates, whose values are not there when the children are counted",
            )


def _refuse_summaries(
    rules: Optional[RulePlan], plugins: Mapping[str, PluginExpose], here: str
) -> None:
    """Refuse a rule that summarises an expose a plugin generates."""
    for rule in () if rules is None else rules.rules:
        if rule.summary is not None and rule.summary[0] in plugins:
            raise _refusal(
                here,
                f"rule {rule.id!r} is an aggregate over {rule.summary[0]!r}, an expose a plugin "
                "generates, whose values are not there when the summary is made",
            )


def _refuse_reads(
    resolved: ResolvedEmit,
    rules: Optional[RulePlan],
    plugins: Mapping[str, PluginExpose],
    *,
    where: str,
) -> None:
    keys = compile_keys(resolved.contract_document)
    if keys is None:
        return
    paths, weights = _paths_of(resolved, rules)
    here = f"{printable(where)}: emit {resolved.expose_id!r}"
    _refuse_summaries(rules, plugins, here)
    _refuse_parent_whens(resolved, keys, plugins, here)
    for path in paths:
        current = resolved.expose_id
        for name in path:
            relationship = next(
                (item for item in keys.expose(current).relationships if item.name == name), None
            )
            if relationship is None:
                break
            if relationship.target in plugins:
                raise _refusal(
                    here,
                    f"it reads a row of {relationship.target!r} through {printable('.'.join(path))}, an "
                    "expose a plugin generates, whose values are not there when this row is made",
                )
            current = relationship.target
    for relationship_name, weight in weights.items():
        relationship = next(
            (
                item
                for item in keys.expose(resolved.expose_id).relationships
                if item.name == relationship_name
            ),
            None,
        )
        target = None if relationship is None else plugins.get(relationship.target)
        if relationship is not None and target is not None and weight in target.names:
            raise _refusal(
                here,
                f"relationship {relationship_name!r} weighs its parents by {weight!r}, a column "
                f"of {relationship.target!r} a plugin generates",
            )
