_EXACT_WEIGHTS = {1: 1.0, 2: 0.5, 4: 0.25, 5: 0.2}


def _renormalised(spec: Dict[str, Any]) -> Dict[str, Any]:
    traits = spec.get("traits")
    if not traits:
        return spec
    fixed = {}
    for name, declared in traits.items():
        if isinstance(declared, dict) and declared.get("dist") == "categorical":
            levels = declared["levels"]
            weight = _EXACT_WEIGHTS.get(len(levels))
            if weight is not None:
                declared = {**declared, "levels": {level: weight for level in levels}}
        fixed[name] = declared
    return {**spec, "traits": fixed}


persona_specs = from_schema(persona_spec_schema(), allow_x00=False, codec="utf-8").map(
    _renormalised
)


def test_persona_specs(tier: Tier, accuracy_log: ResultLog) -> None:
    outcomes = {"ok": 0, "refused": 0}

    @tier.property_settings(pr=60, nightly=1500, label="schema-flux-persona")
    @given(spec=persona_specs, seed=st.integers(0, 2**62))
    def prop(spec: Dict[str, Any], seed: int) -> None:
        document = {**support.small_world().persona, "spec": spec}
        errors = list(flux_validator().iter_errors(document))
        assert not errors, f"the strategy produced an invalid Persona: {errors[0].message}"
        payload = {"spec": spec, "seed": seed, "size": 6}
        with saving_counterexample("schema_flux_persona", payload):
            outcomes[check_persona_spec(payload)] += 1

    prop()
    assert (
        outcomes["ok"] > 0
    ), "no generated Persona ever materialised, so conformance went untested"
    accuracy_log.record(
        family=FAMILY,
        case="schema-flux-persona-specs",
        criterion="FluxError or a population conforming to its declared traits, never another exception",
        passed=True,
        metrics=outcomes,
    )
