def _supported_spellings() -> List[str]:
    candidates = [
        "string", "STRING", "text", "varchar", "varchar(255)", "char(3)", "uuid", "enum",
        "int", "INTEGER", "bigint", "smallint", "int64", "tinyint",
        "bool", "BOOLEAN", "date", "DATE", "timestamp", "TIMESTAMP", "timestamptz",
    ]  # fmt: skip
    accepted = []
    for spelling in candidates:
        try:
            parse_logical_type(spelling)
        except FluxError:
            continue
        accepted.append(spelling)
    return accepted


SUPPORTED_TYPES = _supported_spellings()
DECIMAL_TYPES = st.builds(
    lambda p, s: f"DECIMAL({p},{min(s, p)})", st.integers(1, 38), st.integers(0, 38)
)
TYPE_SPELLING = st.one_of(st.sampled_from(SUPPORTED_TYPES), DECIMAL_TYPES)

raw_columns = from_schema(column_list_schema(), allow_x00=False, codec="utf-8")


def _typed(columns: List[Dict[str, Any]], types: List[str]) -> List[Dict[str, Any]]:
    seen: set = set()
    typed = []
    for index, (column, spelling) in enumerate(zip(columns, types, strict=True)):
        name = column["name"]
        if unicodedata.normalize("NFC", name) in seen:
            name = f"{name}#{index}"
        seen.add(unicodedata.normalize("NFC", name))
        typed.append({**column, "name": name, "type": spelling})
    return typed


typed_columns = raw_columns.flatmap(
    lambda columns: st.lists(TYPE_SPELLING, min_size=len(columns), max_size=len(columns)).map(
        lambda types: _typed(columns, types)
    )
)


def _decimal_text(units: int, scale: int) -> str:
    return format(Decimal(units).scaleb(-scale), "f")


def _timestamp_text(moment: datetime) -> str:
    return moment.strftime("%Y-%m-%dT%H:%M:%S") + f".{moment.microsecond // 1000:03d}Z"


def _ordered(strategy: st.SearchStrategy) -> st.SearchStrategy:
    return st.tuples(strategy, strategy).map(lambda pair: tuple(sorted(pair)))


@st.composite
def fidelity_for(draw: Any, column: Any) -> Dict[str, Any]:
    """Valid aggregate statistics for one compiled column, or none at all."""
    kind, logical = column.logical_type.kind, column.logical_type
    block: Dict[str, Any]
    if kind is LogicalKind.STRING:
        levels = draw(
            st.lists(
                st.text("ABCDEFGH", min_size=1, max_size=3), min_size=1, max_size=4, unique=True
            )
        )
        block = draw(
            st.sampled_from(
                [
                    {"support": {"values": levels}},
                    (
                        {"levels": {level: str(Decimal(1) / len(levels)) for level in levels}}
                        if len(levels) in (1, 2, 4)
                        else {"support": {"values": levels}}
                    ),
                    {},
                ]
            )
        )
    elif kind is LogicalKind.INT:
        lo, hi = draw(_ordered(st.integers(-(10**6), 10**6)))
        block = draw(
            st.sampled_from(
                [
                    {"range": {"min": str(lo), "max": str(hi)}},
                    {"mean": str(draw(st.integers(0, 30)))},
                    {"levels": {"1": "0.5", "2": "0.5"}},
                    {},
                ]
            )
        )
    elif kind is LogicalKind.DECIMAL:
        precision, scale = logical.precision or 1, logical.scale or 0
        top = 10**precision - 1
        lo, hi = draw(_ordered(st.integers(-top, top)))
        block = {"range": {"min": _decimal_text(lo, scale), "max": _decimal_text(hi, scale)}}
        variant = draw(st.sampled_from(["uniformish", "normal", "rate", "none"]))
        if variant == "normal":
            block["mean"] = _decimal_text(draw(st.integers(lo, hi)), scale)
            block["stddev"] = _decimal_text(draw(st.integers(0, top)), scale)
        elif variant == "rate":
            block = {
                "range": {"min": "0", "max": _decimal_text(max(hi, 0), scale)},
                "rate": draw(st.sampled_from(["0.5", "2", "0.001"])),
            }
        elif variant == "none":
            block = {}
    elif kind is LogicalKind.BOOL:
        block = draw(st.sampled_from([{"levels": {"true": "0.3", "false": "0.7"}}, {}]))
    elif kind is LogicalKind.DATE:
        lo, hi = draw(_ordered(st.dates(datetime(2000, 1, 1).date(), datetime(2040, 1, 1).date())))
        block = {"range": {"min": lo.isoformat(), "max": hi.isoformat()}}
    elif kind is LogicalKind.TIMESTAMP:
        lo, hi = draw(_ordered(st.datetimes(datetime(2000, 1, 1), datetime(2040, 1, 1))))
        block = {"range": {"min": _timestamp_text(lo), "max": _timestamp_text(hi)}}
    else:
        block = {}
    null = draw(st.sampled_from([None, None, None, "0", "0.25"]))
    return {**block, **({"nullFraction": null} if null is not None else {})}


def _compile(columns: List[Dict[str, Any]]) -> Any:
    return compile_expose(
        {
            "exposeId": support.EXPOSE_ID,
            "kind": "stream",
            "contract": {"schema": columns},
            "binding": {"platform": "kafka", "format": "kafka_topic", "location": {"topic": "t"}},
        }
    )


def test_fluid_columns_as_generated(tier: Tier, accuracy_log: ResultLog) -> None:
    outcomes = {"ok": 0, "refused": 0}

    @tier.property_settings(pr=60, nightly=600, label="schema-fluid-raw")
    @given(columns=raw_columns, seed=st.integers(0, 2**62))
    def prop(columns: List[Dict[str, Any]], seed: int) -> None:
        payload = {"columns": columns, "fidelity": {}, "seed": seed}
        with saving_counterexample("schema_fluid_columns", payload):
            outcomes[check_fluid_columns(payload)] += 1

    prop()
    accuracy_log.record(
        family=FAMILY,
        case="schema-fluid-columns-as-generated",
        criterion="FluxError or conforming rows, never another exception",
        passed=True,
        metrics=outcomes,
    )


def test_fluid_columns_with_supported_types(tier: Tier, accuracy_log: ResultLog) -> None:
    outcomes = {"ok": 0, "refused": 0}

    @tier.property_settings(pr=60, nightly=800, label="schema-fluid-typed")
    @given(data=st.data(), seed=st.integers(0, 2**62))
    def prop(data: Any, seed: int) -> None:
        columns = data.draw(typed_columns)
        fidelity: Dict[str, Any] = {}
        try:
            compiled = _compile(columns)
        except FluxError:
            outcomes["refused"] += 1
            return
        for column in compiled.columns:
            fidelity[column.name] = data.draw(fidelity_for(column))
        payload = {"columns": columns, "fidelity": fidelity, "seed": seed}
        with saving_counterexample("schema_fluid_columns", payload):
            outcomes[check_fluid_columns(payload)] += 1

    prop()
    assert outcomes["ok"] > 0, "no generated expose was ever accepted, so conformance went untested"
    accuracy_log.record(
        family=FAMILY,
        case="schema-fluid-columns-supported-types",
        criterion="FluxError or conforming rows, never another exception",
        passed=True,
        metrics=outcomes,
    )


