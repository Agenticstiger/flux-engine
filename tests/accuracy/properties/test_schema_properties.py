"""Schema-driven properties: documents valid against the vendored schemas never crash the engine.

``hypothesis-jsonschema`` generates documents that validate against the vendored
FLUID 0.7.5 and FLUX 0.5.0 schemas. Each is spliced into the known-good small bundle
(its Persona, its World, its seam digest) or into a generator plan, and the relevant
engine path runs. **Pass criterion:** the engine either raises
:class:`flux_engine.core.errors.FluxError` (a typed refusal) or succeeds, and what a
success produced conforms to what the document declared; any other exception type is a
failure, as is a value outside its declared type or range, or a generated row the seam
renderer refuses.

What is generated, and what was narrowed (every narrowing is a place the property is
weaker than the schema, and each is here so nobody has to wonder):

* **FLUID ``exposes[].contract.schema[]``.** The array is generated from the schema's own
  ``$defs/column`` (``minItems 1``, ``maxItems 5`` added), with the full ``$defs`` table
  attached so every ``$ref`` resolves. The whole expose is not generated: its
  ``binding``/``qos``/``policy``/``semantics`` blocks are irrelevant to the generator and
  a few of them (``format: uri``, nested ``oneOf``) are slow for hypothesis-jsonschema.
  The expose is the fixed kafka stream the generator tests use.

  * ``test_fluid_columns_as_generated`` uses the columns exactly as generated, with no
    fidelity block. Nearly all are refused (a random ``type`` string, no declared
    statistics), which is the typed-refusal half of the property.
  * ``test_fluid_columns_with_supported_types`` narrows to reach the success half: each
    column's ``type`` is replaced by a spelling the engine claims to support
    (``string``, ``INTEGER``, ``DECIMAL(p,s)``, ``bool``, ``DATE``, ``timestamp``...,
    still valid under the schema's ``type`` pattern), duplicate names are made unique,
    and a fidelity block of valid aggregate statistics is drawn for each compiled
    column (range, support, levels, mean, rate, ``nullFraction``). The FLUX schema does
    not define the fidelity block (it lives in the engine's extension namespace,
    SEAM-FIDELITY-SPEC §2), so that block is generated by hand, not from a schema.
* **FLUX Persona ``spec``.** The ``spec`` sub-schema is lifted out of the FLUX schema's
  ``allOf`` branch for ``kind: Persona``, with the schema's ``$defs`` attached, and
  wrapped in the small bundle's own Persona document (so ``kind`` is a ``const`` by
  construction and ``id``/``name``/``metadata`` are the bundle's). The wrapped document
  is re-validated against the full FLUX schema as a guard on the strategy itself.

  * Strings are generated with ``codec="utf-8"`` and ``allow_x00=False``: a YAML document
    cannot carry a lone surrogate or U+0000, and the engine reads Personas from YAML.
  * The schema does not say that categorical ``levels`` sum to 1 (it is "validator
    enforced"), so almost every generated categorical is refused by the engine
    (``FLX-5020``). For the success half, a categorical with 1, 2, 4 or 5 levels is
    rewritten to weights that sum to exactly 1 (``1``, ``.5``, ``.25``, ``.2``). The
    rewritten document is still valid under the schema.
  * Floats are left as generated, including 5e-324, except that a bounded-normal trait's
    ``mean``, ``stddev``, ``min`` and ``max`` are clamped to +/-1e30. Beyond about 1e38 the
    engine raises a bare ``decimal.InvalidOperation`` (a defect, pinned as a strict xfail
    under ``regressions/``); the clamp keeps the property from re-finding it on every run.
"""

