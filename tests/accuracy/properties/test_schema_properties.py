@lru_cache(maxsize=1)
def flux_schema() -> Dict[str, Any]:
    return json.loads(FLUX_SCHEMA_PATH.read_text(encoding="utf-8"))


@lru_cache(maxsize=1)
def fluid_schema() -> Dict[str, Any]:
    return json.loads(FLUID_SCHEMA_PATH.read_text(encoding="utf-8"))


@lru_cache(maxsize=1)
def flux_validator() -> Draft202012Validator:
    return Draft202012Validator(flux_schema(), format_checker=FormatChecker())


def column_list_schema() -> Dict[str, Any]:
    """``contract.schema[]``: an array of the FLUID schema's own column definition."""
    return {
        "$defs": fluid_schema()["$defs"],
        "type": "array",
        "minItems": 1,
        "maxItems": 5,
        "items": {"$ref": "#/$defs/column"},
    }


def persona_spec_schema() -> Dict[str, Any]:
    """The FLUX schema's ``spec`` for ``kind: Persona``, with the ``$defs`` it points into."""
    for branch in flux_schema()["allOf"]:
        condition = branch.get("if", {}).get("properties", {}).get("kind", {})
        if condition.get("const") == "Persona":
            spec = dict(branch["then"]["properties"]["spec"])
            spec["$defs"] = flux_schema()["$defs"]
            return spec
    raise AssertionError("the FLUX schema has no Persona branch")


